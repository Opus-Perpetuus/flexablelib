"""Regenerate packages/speedups/flexablelib_speedups/_ascii_table.h from
flexablelib._frames.ASCII_FOLD (braille is computed in C, not tabled)."""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from flexablelib._frames import ASCII_FOLD  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), 'packages', 'speedups',
                   'flexablelib_speedups', '_ascii_table.h')


def main():
    pairs = sorted((cp, ch) for cp, ch in ASCII_FOLD.items()
                   if not 0x2800 <= cp <= 0x28FF)
    lines = ['/* Generated by tools/gen_ascii_table.py from',
             ' * flexablelib._frames.ASCII_FOLD. Do not edit. */',
             '', 'struct ascii_fold_entry { Py_UCS4 cp; char ch; };', '',
             'static const struct ascii_fold_entry ascii_fold_table[] = {']
    for cp, ch in pairs:
        lit = {"'": "\\'", '\\': '\\\\'}.get(ch, ch)
        lines.append("    {{0x{0:04X}, '{1}'}},".format(cp, lit))
    lines += ['};', '',
              '#define ASCII_FOLD_COUNT {0}'.format(len(pairs)), '']
    with open(OUT, 'w') as handle:
        handle.write('\n'.join(lines))
    return OUT


if __name__ == '__main__':
    print(main())
